# list using for loops
l = [ 1, 4, 6, 234, 6, 764]

for i in l:
    print(i)


# tuples using for loops
t = (6 ,231 ,75 ,122)

for j in t:
    print(j)


# string using for loops
s = ["harry", "sam", "roman"]

for u in s:
    print(u)


    
for w in range(0,7):   # range(start,stop( n-1 ),steps)  where n = 7
    print(w)        # print 0 to 6 values 